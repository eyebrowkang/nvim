-- lua/plugins/align.lua
-- 按分隔符对齐：mini.align
--
-- 把连续几行按某个字符竖着对齐，让等号、冒号、注释排成一列：
--
--   local a = 1          local a     = 1
--   local bbb = 2   -->  local bbb   = 2
--   local cc = 3         local cc    = 3
--
-- 用法：选中要对齐的几行（V 加 j），按 ga，然后按一下当作分隔符的那个字符。
-- 上面这个例子就是「选中三行 → ga → =」。
--
-- gA 是同一件事，但边按边预览，确认了再按回车。刚上手建议先用 gA 看效果。
--
-- 按下 ga 之后还能先按这些键调整，再按分隔符：
--   s   分隔符要输入多个字符时用（打完按回车）
--   j   切换对齐方向：左对齐 / 居中 / 右对齐
--   t   对齐前先去掉每段两边的空白
--   f   过滤，只对齐符合条件的行
--   <CR>  接受（gA 的预览模式下需要）      <Esc>  放弃
-- 除这些之外按下的任何字符，都直接当作分隔符。

return {
  {
    "nvim-mini/mini.align",

    -- 空表 = 启用，全部用默认。
    -- 默认按键就是下面 keys 里写的 ga / gA。
    opts = {},

    keys = {
      -- 这两条只写了按键、没写要执行什么，是 lazy.nvim 的「纯触发」写法：
      -- 按下时先把插件加载起来，插件在 setup() 里绑好自己的 ga / gA，
      -- 然后 lazy.nvim 把这个键重新发一遍，交给插件真正的映射处理。
      -- 对这种「自己在 setup 里绑键」的插件，这样写比重写一遍映射更省事，
      -- 也不会因为抄错插件内部函数名而失效。
      --
      -- ga 盖住了一个内置命令：打印光标处字符的编码值。
      -- 那个功能用 :ascii 命令一样能得到，没有别的写法丢失。
      { "ga", mode = { "n", "x" }, desc = "按分隔符对齐" },
      { "gA", mode = { "n", "x" }, desc = "按分隔符对齐（带预览）" },
    },
  },
}
