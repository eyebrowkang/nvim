-- lua/plugins/splitjoin.lua
-- 参数列表拆行 / 合行：mini.splitjoin
--
-- 光标停在一对括号里（或括号上），按 gS：
--   本来挤成一行的       →  按逗号拆开，每个参数一行，缩进对齐
--   本来拆成好几行的     →  合并回一行
-- 同一个键来回切换，它自己判断当前是哪种状态。
--
--   f(a, b, c)          --  gS  -->   f(
--                                       a,
--                                       b,
--                                       c
--                                     )
--
-- 对 ( ) [ ] { } 都有效，所以 Lua 的表、JS 的对象、Python 的列表都能用。
-- 手工做的话要换行、调缩进、补逗号，还容易漏掉最后一个元素后面的逗号。

return {
  {
    "nvim-mini/mini.splitjoin",

    opts = {
      mappings = {
        -- 空字符串 = 让插件不要自己绑这个键。
        --
        -- 插件默认把 gS 同时绑在普通模式和可视模式上，而可视模式的 gS
        -- 已经归 nvim-surround 用了（把选中内容包起来并各占一行，见 surround.lua）。
        -- 插件这边没法只关掉可视模式那一个，所以整个关掉，
        -- 由下面的 keys 只补回普通模式的那一个。
        --
        -- 这么写而不是靠「谁后加载谁赢」，是因为加载顺序不该成为配置的一部分：
        -- 哪天加载时机变了，按键会莫名其妙地换主人。
        toggle = "",

        -- split 和 join 默认就是空的（不绑键）。
        -- 单向的拆 / 合很少用得上，gS 一个键来回切就够了。
      },
    },

    keys = {
      {
        "gS",
        function()
          -- 不传参数时它以光标位置为准，自己找最内层的那对括号。
          require("mini.splitjoin").toggle()
        end,
        desc = "参数列表拆行 / 合行",
      },
    },
  },
}
