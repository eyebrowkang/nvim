-- lua/plugins/flash.lua
-- 光标快速跳转：flash
--
-- 按 s 然后输入两个字符，屏幕上所有匹配处会各自冒出一个字母标签，
-- 按那个字母就直接跳过去。目标在屏幕哪个角落都是三次按键。
--
-- 这是本配置里唯一一个「覆盖了原生按键」的插件，下面逐个说明覆盖了什么、
-- 原生功能怎么用别的键做到。不想要的话，把对应那条 keys 删掉即可，
-- 删掉之后原生行为立刻回来。

return {
  {
    "folke/flash.nvim",

    -- 用 VeryLazy 而不是只靠 keys 触发，是因为下面 modes.char 那一段：
    -- f / F / t / T / ; / , 这几个键是插件在 setup() 里自己映射的，
    -- 只写 keys 的话插件要等到你按 s 才加载，在那之前 f 还是原生行为，
    -- 会出现「按一次 s 之后 f 突然变了」这种莫名其妙的现象。
    event = "VeryLazy",

    opts = {
      modes = {
        -- ---- f / F / t / T 的增强 ----
        -- char 模式默认就是开的，插件加载后会接管这六个键。
        -- 增强的部分：按完 f{字符} 之后，再按一次 f 跳下一个、按 F 跳上一个
        -- （不用记 ; 和 , 的方向），同时把这一行里所有匹配都高亮出来。
        char = {
          -- 这一项默认是 true，会让 f 能跨行跳到下面几行去。
          -- 这里改成 false，让 f / t 保持原生的「只在当前行找」语义 ——
          -- 跨行跳有 s，不需要让 f 也变成一个跟标准 Vim 不一样的键。
          multi_line = false,
        },

        -- 顺带说明：modes.search.enabled 默认是 false，
        -- 所以 / 和 ? 的原生搜索完全没被动过。
        -- 想临时在 / 搜索里也用标签跳转，搜索时按下面那个 <C-s> 开关。
      },
    },

    keys = {
      -- ---- s：跳到屏幕上任意位置 ----
      -- 覆盖原生 s（删掉光标处一个字符并进入插入模式）。
      -- 原生等价写法：普通模式 cl，可视模式 c。
      {
        "s",
        mode = { "n", "x", "o" },
        function()
          require("flash").jump()
        end,
        desc = "跳到任意位置",
      },

      -- ---- S：按语法结构选中 ----
      -- 光标停在某处按 S，会把光标所在的语法节点（字符串、函数调用、
      -- 整个函数体……）逐层标出来，按标签直接选中那一层。
      -- 靠的是 treesitter 解析器（见 treesitter.lua），没装解析器的文件类型上不起作用。
      -- 覆盖原生 S（删掉整行并进入插入模式）。原生等价写法：普通模式 cc，可视模式 Vc。
      {
        "S",
        mode = { "n", "x", "o" },
        function()
          require("flash").treesitter()
        end,
        desc = "按语法结构选中",
      },

      -- ---- r：对远处的文本做操作，做完跳回来 ----
      -- 只在「算子待输入」模式生效，也就是必须先按了 d / y / c 这类算子之后才轮到它。
      -- 例如 yr 然后跳到别的位置、再按 iw，就复制了那边的一个词，光标留在原地。
      -- 普通模式的 r（替换单个字符）不受影响，因为这条只映射 o 模式。
      {
        "r",
        mode = "o",
        function()
          require("flash").remote()
        end,
        desc = "对远处文本做操作后跳回",
      },

      -- ---- R：搜索结果里按语法结构选 ----
      -- 同样只在算子待输入和可视模式生效。
      -- 普通模式的 R（进入替换模式）不受影响；可视模式的 R（整行替换）被盖住，
      -- 原生等价写法：Vc。
      {
        "R",
        mode = { "o", "x" },
        function()
          require("flash").treesitter_search()
        end,
        desc = "搜索结果按语法结构选中",
      },

      -- ---- <C-s>：在 / 搜索里开关标签跳转 ----
      -- 只在命令行模式（也就是 / 或 ? 已经按下、正在输入关键词时）生效。
      -- 开启后，搜索的每个命中处都会带一个标签，按标签直接跳到那一处，
      -- 省掉「回车之后按 n 按半天」。
      -- ⚠ 有些终端会把 Ctrl-S 吃掉当作「暂停输出」。
      --   如果按了没反应且终端像卡死，按 Ctrl-Q 恢复，然后把这里换成别的键。
      {
        "<c-s>",
        mode = "c",
        function()
          require("flash").toggle()
        end,
        desc = "搜索时开关标签跳转",
      },
    },
  },
}
