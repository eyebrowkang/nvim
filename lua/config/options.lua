-- lua/config/options.lua
-- 本文件负责 Neovim 的基础选项与全局变量。
--
-- 说明：注释里标注「Neovim 默认」的项，表示不写这行行为也一样，
-- 写出来是为了把意图显式记录下来（也方便你以后知道该改哪一个）。
-- vim.opt / vim.o / vim.g 的区别见 docs/lua-api.md。

local opt = vim.opt

-- 注意：mapleader 不在这里设置，它在 init.lua 最顶部。
-- 原因是 leader 必须早于任何映射被定义，放在这里靠 require 顺序保证太脆弱。

-- ====================================================================
-- 1. 禁用不需要的外部 Provider（消除 :checkhealth 警告，同时略微提速启动）
-- ====================================================================
-- Provider 是 Neovim 调用外部语言运行时来跑老式插件的桥梁。
-- 我们目前 0 插件，也不打算写 Python/Ruby/Perl/Node 插件，全部关掉。
-- 关掉之后 :checkhealth 里对应的告警会变成「disabled」而不是「not found」。
vim.g.loaded_python3_provider = 0
vim.g.loaded_node_provider = 0
vim.g.loaded_perl_provider = 0
vim.g.loaded_ruby_provider = 0

-- ====================================================================
-- 2. 外观与显示
-- ====================================================================
opt.number = true -- 显示绝对行号
opt.relativenumber = true -- 同时显示相对行号：配合 5j / 10k 这类相对跳转，不用心算
opt.cursorline = true -- 高亮光标所在行，长文件里更容易找到自己
opt.signcolumn = "yes" -- 始终保留左侧标记列。设成 "auto" 会在出现 Git/诊断图标时才展开，导致画面横向抖动
opt.termguicolors = true -- 开启 24-bit 真彩色。Neovim 0.10+ 已能自动探测终端并开启，这里显式声明兜底
opt.scrolloff = 8 -- 上下滚动时，光标距离屏幕上下边缘至少保留 8 行
opt.sidescrolloff = 8 -- 左右滚动时，光标距离屏幕左右边缘至少保留 8 列
opt.winborder = "rounded" -- 所有浮动窗口（LSP 悬浮文档、诊断浮窗等）默认用圆角边框

-- showmode 控制最底下那行的 -- INSERT -- 提示。
-- 关掉：模式已经由 lualine 在状态栏左端显示（lua/plugins/lualine.lua），
-- 开着会在屏幕最下方重复一次，还会挤掉命令行区域的其他提示。
-- 注意这是「插件接管了原生功能」，去掉 lualine 就要把它改回 true，
-- 否则 Neovim 自带的 statusline 不显示模式，会完全看不出自己在哪个模式。
opt.showmode = false

-- ====================================================================
-- 3. 缩进与排版
-- ====================================================================
opt.expandtab = true -- 按 Tab 键插入空格而不是制表符
opt.tabstop = 4 -- 一个制表符在屏幕上显示为 4 列宽
opt.shiftwidth = 4 -- 每一级缩进（>> 、<< 、自动缩进）的宽度
opt.softtabstop = 4 -- 插入模式下 Tab/退格 按「4 个空格为一格」来进退
opt.wrap = false -- 关闭软折行：超长行横向滚动，代码对齐关系不被打乱

-- 这里刻意不开 smartindent。它是 Vim 时代的粗糙 C 风格缩进，有两个经典坑：
--   1) 在 Python 里行首输入 # 会被强制顶到第 0 列；
--   2) 输入 { } 时会自作主张地重排缩进。
-- 而 Neovim 默认已经开启 autoindent，并且对绝大多数语言都自带
-- filetype indent（indentexpr），效果比 smartindent 好，也会直接覆盖它。
-- 结论：什么都不设才是最优解，等接了 treesitter 缩进后更是如此。

-- ====================================================================
-- 4. 搜索
-- ====================================================================
opt.ignorecase = true -- 搜索时忽略大小写
opt.smartcase = true -- 但只要你输入了大写字母，就自动切回区分大小写（必须和 ignorecase 一起用才有效）
opt.hlsearch = true -- 高亮所有匹配项（Neovim 默认已开启）
opt.incsearch = true -- 边输入边高亮预览第一个匹配（Neovim 默认已开启）

-- ====================================================================
-- 5. 剪贴板与鼠标
-- ====================================================================
-- 这里刻意不设置 clipboard 选项，保持 Vim 寄存器与系统剪贴板彼此独立：
-- y/d/x/c/p 只在 Vim 内部的寄存器里流转，不会碰系统剪贴板，
-- 也就不会出现「删掉一段代码，顺手覆盖了刚从浏览器复制的内容」。
--
-- 需要和系统交换内容时，显式指定 "+ 寄存器：
--   "+y   复制到系统剪贴板        "+p   粘贴系统剪贴板的内容
--   "+yy  复制当前行到系统剪贴板   "+P   粘贴到光标前
-- （"+ 是系统剪贴板；"* 在 X11 上是鼠标中键的主选区，其他平台等同于 "+）
--
-- "+ 可用与否取决于系统上有没有剪贴板工具，Neovim 启动时按优先级自动探测：
--   macOS       pbcopy / pbpaste，系统自带，开箱即用
--   Linux       Wayland 装 wl-clipboard；X11 装 xsel 或 xclip
--   SSH / 远程  终端支持 OSC 52 即可（Ghostty、kitty、WezTerm 等都支持）
-- 探测顺序见 :help clipboard-tool，排查用 :checkhealth vim.provider。

opt.mouse = "a" -- 所有模式都启用鼠标（默认是 "nvi"，不含命令行模式）

-- ====================================================================
-- 6. 三种文件安全网：swap / backup / undo
-- ====================================================================
-- 这三者作用完全不同，互不替代。文件都放在 $XDG_STATE_HOME/nvim/ 下
-- （一般是 ~/.local/state/nvim/），不会在项目目录里留垃圾。

-- 交换文件（swap）：崩溃恢复 + 多开告警
--   编辑期间 Neovim 把未保存的改动持续写进 .swp 文件，它有两个作用：
--     1) 断电、进程被杀之后，下次打开同一文件会提示可以 :recover 找回未保存的内容；
--     2) 同一个文件被两个 Neovim 实例打开时弹出 E325 告警，防止两边互相覆盖。
--   这两层保护 undofile 都替代不了：undofile 只在 :w 时才写盘，
--   从没保存过的内容它根本不知道。所以保持开启。
--   swap 文件统一放在 ~/.local/state/nvim/swap/，不会污染项目目录。
--   代价：编辑时有持续的磁盘写入；异常退出后残留的 .swp 会让下次打开该文件时
--   多一步手动确认，处理办法见 docs/cheatsheet.md 的「崩溃恢复」。
--   （Neovim 默认就是 true，显式写出以表明这是有意保留的）
opt.swapfile = true

-- 备份文件（backup）：保存时留一份旧版本
--   执行 :w 时，把磁盘上「保存前」的那一版另存一份。
--   默认 backupdir 是 ".,~/.local/state/nvim/backup//"，开头那个 "." 表示
--   优先写在被编辑文件的同目录下，很容易污染项目目录。
--   日常有 git 兜底，不需要它。（这也是 Neovim 的默认值，显式写出）
opt.backup = false

-- 撤销文件（undo）：把撤销历史持久化到磁盘
--   撤销历史默认只存在内存里，关掉 Neovim 就没了。
--   开启后，每次 :w 保存时把整棵撤销树写进 ~/.local/state/nvim/undo/，
--   明天重开同一个文件，仍然可以一路 u 回退到昨天的状态，也能 <C-r> 重做。
--   注意边界：它保护的是「已经保存过的编辑历史」，不是「还没保存的内容」，
--   后者属于上面 swap 的职责。代价只是每个编辑过的文件多一个小文件。
--   配合 :earlier / :later 可以按时间穿越，用法见 docs/cheatsheet.md。
opt.undofile = true

-- ====================================================================
-- 7. 响应速度
-- ====================================================================
opt.updatetime = 250 -- 光标停住多少毫秒后触发 CursorHold（LSP 悬浮、Git 提示的响应速度靠它）

-- timeoutlen：组合键序列中，两次按键之间的最长等待时间（毫秒）。
-- 按下 <leader> 之后有这么久的时间去按下一个键，超时就当作单独的按键处理。
-- 调小更跟手，但按慢了会「按了没反应」；调大更宽容，但按完前缀键会有明显停顿。
opt.timeoutlen = 500

-- ====================================================================
-- 8. 窗口分屏
-- ====================================================================
opt.splitbelow = true -- :split 横向分屏时，新窗口出现在下方（符合阅读直觉）
opt.splitright = true -- :vsplit 纵向分屏时，新窗口出现在右方

-- ====================================================================
-- 9. 诊断显示
-- ====================================================================
-- 「诊断」= 代码里的错误、警告、提示。Neovim 自带一整套收集、显示、跳转的机制，
-- 语言服务器（lua/plugins/lsp.lua）和 nvim-lint（lua/plugins/lint.lua）
-- 都只是把结果投喂给它。既然两边共用同一套显示，配置就放在这里而不是某个插件文件里。
--
-- 这不是 vim.opt 选项而是一次函数调用，但性质和上面那些一样：不依赖任何插件，
-- 插件全删光这段照样生效，只是没有东西往里投喂而已。
--
-- 内置按键，不需要自己映射（:help diagnostic-defaults）：
--   <C-w>d    浮窗显示光标所在行的诊断全文
--   ]d  [d    跳到下一条 / 上一条诊断
--   ]D  [D    跳到本文件最后一条 / 第一条诊断
vim.diagnostic.config({
  -- 同一行同时有错误和提示时，让最严重的那条决定标记列显示什么。
  -- 默认 false 的话取的是最后收到的那条，可能是个提示把错误盖掉了。
  severity_sort = true,

  -- 左侧标记列（signcolumn）的图标，默认是 E / W / I / H 四个字母。
  -- 这四个图标和 lualine 状态栏上诊断计数用的是同一组，标记列和状态栏对得上。
  -- 它们来自 Nerd Font，字体没配好会显示成豆腐块，那就把整个 signs 删掉用回字母。
  signs = {
    text = {
      [vim.diagnostic.severity.ERROR] = "󰅚 ",
      [vim.diagnostic.severity.WARN] = "󰀪 ",
      [vim.diagnostic.severity.INFO] = "󰋽 ",
      [vim.diagnostic.severity.HINT] = "󰌶 ",
    },
  },

  -- 把诊断文字直接显示在代码右侧。默认是关的。
  -- current_line = true 表示「只显示光标所在行的那条」，其他行仍然只有左侧图标。
  -- 不加这个限制的话，一屏里有几处报错就拖几条尾巴，很快就看不清代码本身了。
  -- 想看别处的，把光标移过去，或者按 <C-w>d 开浮窗。
  virtual_text = { current_line = true, prefix = "●" },

  -- 没开 virtual_lines：那是把诊断另起一行显示在代码下方，长消息读起来确实清楚，
  --   但它会把下面的代码整体推开，光标一动版面就跳。要试的话：
  --     virtual_lines = { current_line = true }
  --   （同时得把上面的 virtual_text 关掉，否则一条诊断显示两遍）
  --
  -- 没开 update_in_insert：默认就是 false，即插入模式下不刷新诊断。
  --   开了会在一句话写到一半时满屏报错，写完自然就消失，纯粹是干扰。
})
