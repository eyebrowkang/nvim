-- lua/config/keymaps.lua
-- 本文件定义全局通用快捷键，不依赖任何第三方插件。
--
-- vim.keymap.set(mode, lhs, rhs, opts) 的几个要点：
--   mode  模式名，可以是字符串或字符串数组。常用："n" 普通、"i" 插入、
--         "x" 可视(Visual)、"s" 选择(Select)、"v" = x + s、"t" 终端。
--   opts  常用字段：desc 描述（会显示在 :map 和 which-key 里）、
--         silent 不在命令行回显、expr 把 rhs 当表达式求值。
--   注意：vim.keymap.set 默认就是 noremap = true（不递归），不用手写。
--
-- 保持克制：Neovim 自带一批默认映射（:help default-mappings），
-- 想要的行为如果内置已经有了，就不要再映射一遍。清单见 docs/cheatsheet.md。

local map = vim.keymap.set

-- 小工具：统一补上 silent = true，只需要传一句描述。
-- 这样每行映射不用重复写 { desc = "...", silent = true }。
local function opts(desc)
  return { desc = desc, silent = true }
end

-- ====================================================================
-- 1. 窗口尺寸调整
-- ====================================================================
-- 用 Ctrl + 方向键调整分屏大小。
-- 选 Ctrl 而不是 Alt，是因为 Alt 在终端里的传递最不可靠：
-- macOS 上 Option 默认被当作输入特殊字符的组合键而不是 Alt，
-- 部分 Linux 终端也会把 Alt 组合吃掉。Ctrl + 方向键则各终端表现一致。
map("n", "<C-Up>", "<cmd>resize +2<CR>", opts("增加窗口高度"))
map("n", "<C-Down>", "<cmd>resize -2<CR>", opts("减少窗口高度"))
map("n", "<C-Left>", "<cmd>vertical resize -2<CR>", opts("减少窗口宽度"))
map("n", "<C-Right>", "<cmd>vertical resize +2<CR>", opts("增加窗口宽度"))

-- ====================================================================
-- 2. 可视模式增强
-- ====================================================================
-- 下面全部用 "x"（纯 Visual 模式）。
-- 不能用 "v"，因为 "v" 等于 Visual + Select 两种模式；
-- Select 模式下按任意可打印字符应当是「替换选中内容」，
-- 把 J/K/</> 映射进去，以后用代码片段(snippet)跳转占位符时就会出怪事。
-- 规则：处理选区行为的映射一律用 "x"。

-- 整块上下移动选中的行
--   :m '>+1  把选区移动到「选区最后一行的下一行」之后
--   gv       重新选中刚才那块（:m 之后选区会丢失）
--   =        对选区重新做一次自动缩进
map("x", "J", ":m '>+1<CR>gv=gv", opts("向下移动选中的行"))
map("x", "K", ":m '<-2<CR>gv=gv", opts("向上移动选中的行"))

-- 连续缩进：缩进后自动重新选中，可以连着按 < 或 >
map("x", "<", "<gv", opts("向左缩进并保持选中"))
map("x", ">", ">gv", opts("向右缩进并保持选中"))

-- ====================================================================
-- 3. 系统剪贴板
-- ====================================================================
-- options.lua 里刻意没设 clipboard 选项，y/d/p 只走 Vim 自己的寄存器，
-- 和系统剪贴板互不干扰。需要跨程序传内容时才走这组 <leader> 映射，
-- 相当于把 "+ 前缀提前按好了。
--
-- 记法：和原生的 y / yy / p / P 完全对应，只是前面多按一个 <leader>。
--   <leader>y{motion}  复制一个范围，如 <leader>yiw 复制光标下的词、<leader>yap 复制整段
--   <leader>yy         复制当前行
--   <leader>y          在可视模式下 = 复制选中区域
-- <leader>y 既是完整映射、又是 <leader>yy 的前缀，这是 Vim 里 y / yy 一样的结构：
-- 下一个键不是 y 就立刻当作动作处理，不会互相干扰。
map({ "n", "x" }, "<leader>y", '"+y', opts("复制到系统剪贴板"))
map("n", "<leader>yy", '"+yy', opts("复制当前行到系统剪贴板"))

-- 这里不写成 '"+Y'：映射默认不递归，'"+Y' 会落到内建的 Y（整行），
-- 而不是 Neovim 默认映射里的 Y（= y$，复制到行尾）。直接写 y$ 意图更清楚。
map("n", "<leader>Y", '"+y$', opts("复制到行尾（系统剪贴板）"))

-- 粘贴系统剪贴板的内容。可视模式下用它替换选区是安全的：
-- 被替换掉的内容进的是无名寄存器，不会把 + 里的内容冲掉，可以连续粘贴多次。
map({ "n", "x" }, "<leader>p", '"+p', opts("粘贴系统剪贴板"))
map({ "n", "x" }, "<leader>P", '"+P', opts("粘贴系统剪贴板到光标前"))

-- 注意：这组映射能不能用，取决于系统上装没装剪贴板工具
-- （macOS 自带 pbcopy；Linux 需要 wl-clipboard 或 xsel/xclip）。
-- 缺工具时按下去会报 clipboard provider 相关的错，用 :checkhealth vim.provider 排查。

-- ====================================================================
-- 4. 内嵌提示开关
-- ====================================================================
-- 内嵌提示（inlay hints）默认开着，在 options.lua 第 9 节打开。
-- 这里给一个临时开关：读一段陌生代码时它很有用，但要数对齐、要截图、
-- 或者提示比代码本身还长的时候，按一下先关掉。
--
-- 不传第二个参数就是全局开关，和 options.lua 里那次调用作用范围一致。
-- 只想关当前这个文件的话把参数写全：
--   vim.lsp.inlay_hint.enable(false, { bufnr = 0 })
map("n", "<leader>ch", function()
  vim.lsp.inlay_hint.enable(not vim.lsp.inlay_hint.is_enabled())
end, opts("开关内嵌提示"))
