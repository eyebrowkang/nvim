-- init.lua
-- Neovim 配置总入口。
-- 这个文件只做三件事：开启模块缓存 → 定义 leader 键 → 按顺序加载模块。
-- 具体的配置内容都在 lua/config/ 下，入口保持干净，方便一眼看清加载顺序。

-- ====================================================================
-- 1. 启用 Lua 模块字节码缓存（纯性能优化）
-- ====================================================================
-- vim.loader 会把 require 过的 Lua 模块编译结果缓存到磁盘，
-- 下次启动直接读缓存，省掉重复的解析/编译开销。
-- 它按文件修改时间自动失效，所以你改完配置不需要手动清缓存。
-- 必须放在所有 require 之前，否则前面的 require 享受不到缓存。
vim.loader.enable()

-- ====================================================================
-- 2. Leader 键声明（必须早于任何按键映射与插件加载）
-- ====================================================================
-- 为什么必须最早：<leader> 在「定义映射的那一刻」就被解析成具体按键并写死，
-- 之后再改 mapleader 也不会回头修正已经定义好的映射。
-- 顺序搞反的结果是：所有 <leader> 映射都会变成默认的反斜杠 \ 触发。
-- 全仓库只在这里设置一次，其他文件不要重复设置。
vim.g.mapleader = " " -- 全局 leader：空格键
vim.g.maplocalleader = " " -- 局部 leader（只在特定 filetype 生效的映射用它）：同样是空格

-- ====================================================================
-- 3. 加载核心原生模块
-- ====================================================================
-- 顺序：选项 → 按键 → 自动命令 → 文件类型。
-- require("config.options") 对应文件 lua/config/options.lua，
-- Lua 里的点号会被翻译成路径分隔符，并在 runtimepath 的 lua/ 目录下查找。
require("config.options") -- 基础选项：行号、缩进、搜索、剪贴板、持久化…
require("config.keymaps") -- 全局快捷键：窗口导航、可视模式行移动…
require("config.autocmds") -- 自动命令：复制高亮、恢复光标位置、q 关闭辅助窗口
require("config.filetype") -- 文件类型识别补充：Ansible 的 YAML、Jinja 模板

-- ====================================================================
-- 4. 插件
-- ====================================================================
-- 必须排在最后：lazy.nvim 会接管启动流程并开始加载插件，
-- 而插件加载时会读取此前设好的选项（如 termguicolors）和 leader 键。
-- 上面三行都是纯原生配置，即使插件全部出问题也照常生效。
--
-- config.lazy 只负责「装好并启动 lazy.nvim」；
-- 具体要装哪些插件写在 lua/plugins/ 下，由它自动导入。
require("config.lazy")
